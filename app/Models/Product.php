<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\Storage;

class Product extends Model
{
    use HasFactory;

    /*
    |--------------------------------------------------------------------------
    | TABLE
    |--------------------------------------------------------------------------
    */

    protected $table = 'products';

    /*
    |--------------------------------------------------------------------------
    | MASS ASSIGNMENT
    |--------------------------------------------------------------------------
    */

    protected $fillable = [

        'supplier_id',

        'name',

        'description',

        'price',

        'stock',

        'image',

        'category',

    ];

    /*
    |--------------------------------------------------------------------------
    | CASTS
    |--------------------------------------------------------------------------
    */

    protected $casts = [

        'price' => 'integer',

        'stock' => 'integer',

    ];

    /*
    |--------------------------------------------------------------------------
    | APPENDS
    |--------------------------------------------------------------------------
    */

    protected $appends = [

        'image_url'

    ];

    /*
    |--------------------------------------------------------------------------
    | RELATIONSHIP
    |--------------------------------------------------------------------------
    */

    public function supplier()
    {
        return $this->belongsTo(Supplier::class);
    }

    /*
    |--------------------------------------------------------------------------
    | IMAGE URL ACCESSOR
    |--------------------------------------------------------------------------
    */

    public function getImageUrlAttribute(): string
    {
        /*
        |--------------------------------------------------------------------------
        | PLACEHOLDER
        |--------------------------------------------------------------------------
        */

        $placeholder = asset(
            'images/placeholder-product.png'
        );

        $image = (string) ($this->image ?? '');

        /*
        |--------------------------------------------------------------------------
        | EMPTY
        |--------------------------------------------------------------------------
        */

        if ($image === '') {

            return $placeholder;

        }

        /*
        |--------------------------------------------------------------------------
        | ABSOLUTE URL
        |--------------------------------------------------------------------------
        */

        if (preg_match('~^https?://~', $image)) {

            return $image;

        }

        /*
        |--------------------------------------------------------------------------
        | FILE NAME
        |--------------------------------------------------------------------------
        */

        $raw = ltrim($image, '/');

        $file = basename($raw);

        /*
        |--------------------------------------------------------------------------
        | STORAGE
        |--------------------------------------------------------------------------
        */

        foreach ([

            "products/{$file}",

            $raw

        ] as $path) {

            if (
                Storage::disk('public')->exists($path)
            ) {

                return asset(
                    'storage/' . $path
                );

            }

        }

        /*
        |--------------------------------------------------------------------------
        | PUBLIC
        |--------------------------------------------------------------------------
        */

        foreach ([

            "images/products/{$file}",

            $raw

        ] as $path) {

            if (
                file_exists(public_path($path))
            ) {

                return asset($path);

            }

        }

        /*
        |--------------------------------------------------------------------------
        | FALLBACK
        |--------------------------------------------------------------------------
        */

        return $placeholder;
    }

    /*
    |--------------------------------------------------------------------------
    | CATEGORY SCOPE
    |--------------------------------------------------------------------------
    */

    public function scopeCategory(
        $query,
        ?string $category
    ) {
        if ($category) {

            $query->where(
                'category',
                $category
            );

        }

        return $query;
    }
}